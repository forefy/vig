func v(s string) Version {
	ver, err := ParseVersion(s)
	if err != nil {
		panic(err)
	}
	return ver
}

func TestParseVersion(t *testing.T) {
	cases := []struct {
		in      string
		want    Version
		wantErr bool
	}{
		{"1.2.3", Version{1, 2, 3, ""}, false},
		{"1.2", Version{1, 2, 0, ""}, false},
		{"1", Version{1, 0, 0, ""}, false},
		{"v1.2.3", Version{1, 2, 3, ""}, false},
		{" 1.2.3 ", Version{1, 2, 3, ""}, false},
		{"1.2.3-alpha.1", Version{1, 2, 3, "alpha.1"}, false},
		{"1.2.3-rc-2", Version{1, 2, 3, "rc-2"}, false},
		{"1.2.3+build.5", Version{1, 2, 3, ""}, false},
		{"1.2.3-beta+exp.sha.5114f85", Version{1, 2, 3, "beta"}, false},
		{"0.0.0", Version{}, false},
		{"", Version{}, true},
		{"abc", Version{}, true},
		{"1.2.3.4", Version{}, true},
		{"1..2", Version{}, true},
		{"-1.0.0", Version{}, true},
		{"1.0.0-", Version{}, true},
		{"^1.0.0", Version{}, true},
	}
	for _, c := range cases {
		got, err := ParseVersion(c.in)
		if (err != nil) != c.wantErr {
			t.Errorf("ParseVersion(%q) err=%v wantErr=%v", c.in, err, c.wantErr)
			continue
		}
		if got != c.want {
			t.Errorf("ParseVersion(%q)=%+v want %+v", c.in, got, c.want)
		}
	}
}

func TestCompare(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		{"1.0.0", "1.0.0", 0},
		{"1.0.0", "1.0.1", -1},
		{"1.1.0", "1.0.9", 1},
		{"2.0.0", "1.99.99", 1},
		{"0.9.0", "1.0.0", -1},
		{"1.0.0-alpha", "1.0.0", -1},
		{"1.0.0", "1.0.0-alpha", 1},
		{"1.0.0-alpha", "1.0.0-beta", -1},
		{"1.0.0-beta", "1.0.0-alpha", 1},
		{"1.0.0-alpha", "1.0.0-alpha", 0},
		{"1.0.1-alpha", "1.0.0", 1},
		{"1.0.0+a", "1.0.0+b", 0},
	}
	for _, c := range cases {
		if got := Compare(v(c.a), v(c.b)); got != c.want {
			t.Errorf("Compare(%s, %s)=%d want %d", c.a, c.b, got, c.want)
		}
		if got := Compare(v(c.b), v(c.a)); got != -c.want {
			t.Errorf("Compare(%s, %s) is not antisymmetric", c.b, c.a)
		}
	}
}

func TestMatchReq(t *testing.T) {
	cases := []struct {
		req  string
		ver  string
		want bool
	}{
		// wildcards
		{"*", "0.0.1", true},
		{"", "9.9.9", true},
		{"  ", "1.0.0", true},
		// comparison operators
		{">= 1.2.0", "1.2.0", true},
		{">= 1.2.0", "1.1.9", false},
		{">=1.2.0", "1.3.0", true},
		{"> 1.2.3", "1.2.3", false},
		{"> 1.2.3", "1.2.4", true},
		{"<= 1.2.3", "1.2.3", true},
		{"<= 1.2.3", "1.2.4", false},
		{"< 2.0.0", "1.99.99", true},
		{"< 2.0.0", "2.0.0", false},
		{"< 2", "1.9.9", true},
		{"< 2", "2.0.0", false},
		// compound
		{">= 1.2.0, < 2.0.0", "1.2.0", true},
		{">= 1.2.0, < 2.0.0", "1.9.9", true},
		{">= 1.2.0, < 2.0.0", "2.0.0", false},
		{">= 1.2.0, < 2.0.0", "1.1.9", false},
		{">=1.2.0,<2.0.0", "1.5.0", true},
		{">= 0.3.0, < 0.3.5", "0.3.4", true},
		{">= 0.3.0, < 0.3.5", "0.3.5", false},
		// exact
		{"= 2.0.1", "2.0.1", true},
		{"= 2.0.1", "2.0.2", false},
		{"=2.0", "2.0.7", true},
		{"=2.0", "2.1.0", false},
		{"= 2", "2.9.9", true},
		{"= 2", "3.0.0", false},
		// caret (also the default for a bare version)
		{"^1.2.3", "1.2.3", true},
		{"^1.2.3", "1.9.0", true},
		{"^1.2.3", "2.0.0", false},
		{"^1.2.3", "1.2.2", false},
		{"1.2.3", "1.9.0", true},
		{"1.2.3", "2.0.0", false},
		{"^1", "1.0.0", true},
		{"^1", "1.9.9", true},
		{"^1", "2.0.0", false},
		{"^0.3", "0.3.0", true},
		{"^0.3", "0.3.9", true},
		{"^0.3", "0.4.0", false},
		{"^0.3", "0.2.9", false},
		{"^0.3.2", "0.3.5", true},
		{"^0.3.2", "0.3.1", false},
		{"^0.3.2", "0.4.0", false},
		{"^0.0.3", "0.0.3", true},
		{"^0.0.3", "0.0.4", false},
		{"^0.0.3", "0.0.2", false},
		{"^0.0", "0.0.9", true},
		{"^0.0", "0.1.0", false},
		{"^0", "0.9.9", true},
		{"^0", "1.0.0", false},
		// tilde
		{"~1.4", "1.4.0", true},
		{"~1.4", "1.4.9", true},
		{"~1.4", "1.5.0", false},
		{"~1.4", "1.3.9", false},
		{"~1", "1.9.9", true},
		{"~1", "2.0.0", false},
		{"~1.4.2", "1.4.2", true},
		{"~1.4.2", "1.4.9", true},
		{"~1.4.2", "1.4.1", false},
		{"~1.4.2", "1.5.0", false},
		// pre-release ordering as implemented: a pre-release sorts below its release
		{"< 1.0.0", "1.0.0-alpha", true},
		{">= 1.0.0", "1.0.0-alpha", false},
		{">= 1.0.0-alpha", "1.0.0-beta", true},
		{">= 1.0.0-beta", "1.0.0-alpha", false},
		{"^1.0.0-alpha", "1.0.0", true},
		{"= 1.0.0-rc.1", "1.0.0-rc.1", true},
		{"= 1.0.0-rc.1", "1.0.0", false},
		// garbage requirements never match
		{"abc", "1.0.0", false},
		{">= abc", "1.0.0", false},
		{">= 1.0.0, abc", "1.0.0", false},
		{"1.0.0.0", "1.0.0", false},
	}
	for _, c := range cases {
		if got := MatchReq(c.req, v(c.ver)); got != c.want {
			t.Errorf("MatchReq(%q, %s)=%v want %v", c.req, c.ver, got, c.want)
		}
	}
}

func TestParseCargoLock(t *testing.T) {
	lock := `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "anchor-lang"
version = "0.29.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
dependencies = [
 "anchor-attribute-access-control",
 "solana-program",
]

[[package]]
name = "solana-program"
version = "1.17.6"

[[package]]
name = "solana-program"
version = "1.18.0"

[[package]]
version = "9.9.9"

[[package]]
name = "vault"
version = "0.1.0"
dependencies = [
 "anchor-lang",
]
`
	got := ParseCargoLock(lock)
	want := []Package{{"anchor-lang", "0.29.0"}, {"solana-program", "1.17.6"}, {"solana-program", "1.18.0"}, {"vault", "0.1.0"}}
	if len(got) != len(want) {
		t.Fatalf("got %+v want %+v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("[%d] got %+v want %+v", i, got[i], want[i])
		}
	}
	if ParseCargoLock("") != nil {
		t.Fatal("empty lock yields nil")
	}
	if ParseCargoLock("name = \"x\"\nversion = \"1\"\n") != nil {
		t.Fatal("entries outside [[package]] are ignored")
	}
	if got := ParseCargoLock("[[package]]\r\nname = \"crlf\"\r\nversion = \"1.0.0\"\r\n"); len(got) != 1 || got[0] != (Package{"crlf", "1.0.0"}) {
		t.Fatalf("crlf: %+v", got)
	}
}

func TestReadCargoLock(t *testing.T) {
	dir := t.TempDir()
	if ReadCargoLock(filepath.Join(dir, "Cargo.lock")) != nil {
		t.Fatal("missing lock is nil")
	}
	os.WriteFile(filepath.Join(dir, "Cargo.lock"), []byte("[[package]]\nname = \"a\"\nversion = \"1.0.0\"\n"), 0o644)
	if got := ReadCargoLock(filepath.Join(dir, "Cargo.lock")); len(got) != 1 || got[0] != (Package{"a", "1.0.0"}) {
		t.Fatalf("got %+v", got)
	}
}
